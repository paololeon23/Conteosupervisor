/** @deprecated usar SUPERVISORES */
export const SUPERVISORES_FIJOS = SUPERVISORES.map((s) => s.nombre);

export function getSupervisores() {
  return SUPERVISORES.map((s) => ({ ...s }));
}

export function limpiarDni(raw) {
  return String(raw || '').replace(/\D/g, '').slice(0, 9);
}

export function buscarPorDni(dni) {
  const code = limpiarDni(dni);
  if (code.length < 8) return null;
  return SUPERVISORES.find((s) => s.dni === code) || null;
}

/** Extrae DNI del campo Supervisor en Sheet: "42493820 · NOMBRE" */
export function extraerDni(supervisorField) {
  const s = String(supervisorField || '').trim();
  const m = s.match(/^(\d{8,9})\b/);
  return m ? m[1] : '';
}

export function etiquetaSupervisor(dni, nombre) {
  const code = limpiarDni(dni);
  const nom = String(nombre || '').trim().toUpperCase();
  if (code && nom) return `${code} · ${nom}`;
  return nom || code;
}

export function nombreVisible(supervisorField) {
  const s = String(supervisorField || '').trim();
  const m = s.match(/^\d{8,9}\s*[·\-–]?\s*(.+)$/);
  return (m ? m[1] : s).trim();
}

function normalizarNombreSup(nombre) {
  return String(nombre || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Relaciona texto del Excel (con o sin DNI) a un supervisor fijo */
export function matchSupervisorFijo(nombreReportado) {
  const dni = extraerDni(nombreReportado);
  if (dni) {
    const byDni = buscarPorDni(dni);
    if (byDni) return byDni;
  }

  const n = normalizarNombreSup(nombreVisible(nombreReportado));
  const compact = n.replace(/\s+/g, '');
  if (!n) return null;

  for (const s of SUPERVISORES) {
    const f = normalizarNombreSup(s.nombre);
    if (f === n || f.replace(/\s+/g, '') === compact) return s;
  }

  const candidatos = SUPERVISORES.filter((s) => {
    const f = normalizarNombreSup(s.nombre);
    return f.includes(n) || n.includes(f);
  });
  if (candidatos.length === 1) return candidatos[0];
  return null;
}

/** DNIs del catálogo fijo que ya tienen conteo en la data reportada */
function dniReportados_(reportados = []) {
  const matched = new Set();
  for (const r of reportados) {
    const nombre = typeof r === 'string' ? r : r?.supervisor;
    const hit = matchSupervisorFijo(nombre);
    if (hit) matched.add(hit.dni);
  }
  return matched;
}

/** Supervisores fijos sin conteo en la data reportada */
export function supervisoresFaltantes(reportados = []) {
  const matched = dniReportados_(reportados);
  return SUPERVISORES.filter((s) => !matched.has(s.dni));
}

/** Supervisores fijos que ya reportaron */
export function supervisoresPresentes(reportados = []) {
  const matched = dniReportados_(reportados);
  return SUPERVISORES.filter((s) => matched.has(s.dni));
}

/**
 * Validación completa: quién reportó y quién falta.
 * @returns {{ presentes: object[], faltan: object[], total: number }}
 */
export function validarSupervisores(reportados = []) {
  const matched = dniReportados_(reportados);
  const presentes = SUPERVISORES.filter((s) => matched.has(s.dni));
  const faltan = SUPERVISORES.filter((s) => !matched.has(s.dni));
  return { presentes, faltan, total: SUPERVISORES.length };
}

export function filtrarSupervisores(query, lista = SUPERVISORES) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return [...lista];
  const digits = q.replace(/\D/g, '');
  return lista.filter((s) => {
    if (digits && s.dni.includes(digits)) return true;
    return s.nombre.toLowerCase().includes(q);
  });
}
